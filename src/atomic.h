#ifndef MCC_ATOMIC_H
#define MCC_ATOMIC_H

typedef enum {
    AT_LOAD, AT_STORE, AT_EXCHANGE, AT_COMPARE,
    AT_ADD, AT_SUB, AT_AND, AT_OR, AT_XOR, AT_NAND,
    AT_TEST_AND_SET, AT_CLEAR, AT_THREAD_FENCE, AT_SIGNAL_FENCE, AT_LOCK_FREE, AT_UNLOCK
} AtomicOperation;

enum {
    AT_OPERATION_MASK = 127, AT_POINTER_ARGUMENTS = 128, AT_RETURN_NEW = 256,
    AT_EXPECTED_VALUE = 512, AT_RETURN_OBSERVED = 1024
};

#endif
